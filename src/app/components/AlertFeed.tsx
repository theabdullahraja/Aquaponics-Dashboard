import { AlertTriangle, Info, AlertCircle, X } from 'lucide-react';
import { useState } from 'react';

interface Alert {
  id: string;
  severity: 'critical' | 'warning' | 'info';
  title: string;
  description: string;
  timestamp: string;
}

export function AlertFeed() {
  const [alerts, setAlerts] = useState<Alert[]>([
    {
      id: '1',
      severity: 'warning',
      title: 'pH Dropping',
      description: 'Current: 6.8 (Optimal: 7.0-7.5)',
      timestamp: '14 mins ago',
    },
    {
      id: '2',
      severity: 'info',
      title: 'Water Pump Cycle Complete',
      description: 'Next cycle scheduled in 2 hours',
      timestamp: '1 hour ago',
    },
    {
      id: '3',
      severity: 'critical',
      title: 'Low Water Level',
      description: 'Current: 62% (Minimum: 65%)',
      timestamp: '3 hours ago',
    },
  ]);

  const getAlertConfig = (severity: Alert['severity']) => {
    switch (severity) {
      case 'critical':
        return {
          icon: AlertCircle,
          color: '#EF4444',
          bg: '#EF444410',
        };
      case 'warning':
        return {
          icon: AlertTriangle,
          color: '#F59E0B',
          bg: '#F59E0B10',
        };
      case 'info':
        return {
          icon: Info,
          color: '#0EA5E9',
          bg: '#0EA5E910',
        };
    }
  };

  const dismissAlert = (id: string) => {
    setAlerts(alerts.filter((alert) => alert.id !== id));
  };

  return (
    <div className="space-y-6">
      <div>
        <h2 className="text-2xl font-semibold text-foreground">Recent Alerts</h2>
        <p className="text-sm text-muted-foreground mt-1">Threshold and fault notifications generated by the ESP32-S3 rule engine</p>
      </div>

      <div className="space-y-4">
        {alerts.map((alert) => {
          const config = getAlertConfig(alert.severity);
          const Icon = config.icon;

          return (
            <div
              key={alert.id}
              className="bg-card rounded-lg p-5 border-l-4 border-border-subtle hover:shadow-lg transition-all duration-200 group relative"
              style={{
                borderLeftColor: config.color,
                backgroundColor: config.bg,
              }}
            >
              <div className="flex items-start gap-4">
                <div
                  className="w-10 h-10 rounded-lg flex items-center justify-center flex-shrink-0"
                  style={{
                    backgroundColor: `${config.color}20`,
                  }}
                >
                  <Icon className="w-5 h-5" style={{ color: config.color }} />
                </div>

                <div className="flex-1 min-w-0">
                  <h3 className="text-lg font-semibold text-foreground mb-1">{alert.title}</h3>
                  <p className="text-sm text-muted-foreground mb-2">{alert.description}</p>
                  <p className="text-xs text-muted-foreground">{alert.timestamp}</p>

                  <div className="flex gap-3 mt-4">
                    <button className="text-sm font-medium px-4 py-1.5 rounded-lg border border-border-subtle hover:bg-surface-dark transition-colors">
                      View Details
                    </button>
                    <button
                      onClick={() => dismissAlert(alert.id)}
                      className="text-sm font-medium px-4 py-1.5 rounded-lg hover:bg-surface-dark transition-colors text-muted-foreground"
                    >
                      Dismiss
                    </button>
                  </div>
                </div>

                <button
                  onClick={() => dismissAlert(alert.id)}
                  className="opacity-0 group-hover:opacity-100 transition-opacity p-1 hover:bg-surface-dark rounded-lg"
                >
                  <X className="w-4 h-4 text-muted-foreground" />
                </button>
              </div>

              {alert.severity === 'critical' && (
                <div
                  className="absolute inset-0 rounded-lg pointer-events-none"
                  style={{
                    boxShadow: `0 0 20px ${config.color}30`,
                    animation: 'pulse 2s cubic-bezier(0.4, 0, 0.6, 1) infinite',
                  }}
                />
              )}
            </div>
          );
        })}
      </div>
    </div>
  );
}
